        public static char Normalize(char c)
        {
            c = char.ToUpperInvariant(c);
            switch (c)
            {
                case 'É': case 'È': case 'Ê': case 'Ë': return 'E';
                case 'À': case 'Â': case 'Ä': return 'A';
                case 'Î': case 'Ï': return 'I';
                case 'Ô': case 'Ö': return 'O';
                case 'Ù': case 'Û': case 'Ü': return 'U';
                case 'Ç': return 'C';
                case '’': return '\'';
                default: return c;
            }
        }

        /// <summary>Renvoie true si le pixel (gx, gy) du glyphe est allumé (gy = 0 en haut).</summary>
        public static bool Pixel(char c, int gx, int gy)
        {
            Init();
            if (!glyphs.TryGetValue(Normalize(c), out var rows)) return false;
            if (gy < 0 || gy >= GlyphH || gx < 0 || gx >= GlyphW) return false;
            return rows[gy][gx] == '#';
        }

        public static int TextWidth(string text, int scale)
        {
            if (string.IsNullOrEmpty(text)) return 0;
            return text.Length * (GlyphW + 1) * scale - scale;
        }
